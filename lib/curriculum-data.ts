import type { FieldKey } from "@/lib/types";

export interface CurriculumSubtopic {
  id: string;
  title: string;
}
export interface CurriculumTopic {
  id: string;
  number: string;
  title: string;
  subtopics: CurriculumSubtopic[];
}
export interface CurriculumPhase {
  id: string;
  number: number;
  title: string;
  subtitle: string;
  duration: string;
  topics: CurriculumTopic[];
}
export interface CurriculumField {
  key: FieldKey;
  name: string;
  tagline: string;
  phases: CurriculumPhase[];
}

const slug = (parts: string[]) =>
  parts
    .join("-")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");

function topic(field: FieldKey, phaseN: number, number: string, title: string, subs: string[]): CurriculumTopic {
  return {
    id: slug([field, "p" + phaseN, number, title]),
    number,
    title,
    subtopics: subs.map((s) => ({ id: slug([field, "p" + phaseN, number, s]), title: s })),
  };
}

